local CharacterRoleCtrl = {
	keyWord = "ID",
	keyWordNum = 1,
	hasCached = false
}
local CharacterRole = {}

function CharacterRole:GetAllSync()
	if CharacterRoleCtrl.hasCached then
		return
	end

	local rowsList = SqlLiteSupport.ExecuteQuery("CharacterRole", "select * from CharacterRole")

	rowsList:ForEach(function(v)
		local jsonTb = SqlLiteTransfer.TransferFromJson(v, CharacterRoleInfo)
		local keyWord = SqlLiteTransfer.GetKeyWord(CharacterRoleCtrl, jsonTb)

		self[keyWord] = jsonTb
	end)

	CharacterRoleCtrl.hasCached = true
	CharacterRole.GetAllSync = nil
	CharacterRole.GetAllASync = nil
end

function CharacterRole:GetAllASync()
	if CharacterRoleCtrl.hasCached then
		return
	end

	SqlLiteSupport.LazyCacheData("CharacterRole", "select * from CharacterRole", function()
		local rowsList = SqlLiteSupport.GetCacheData("CharacterRole")

		rowsList:ForEach(function(v)
			local jsonTb = SqlLiteTransfer.TransferFromJson(v, CharacterRoleInfo)
			local keyWord = SqlLiteTransfer.GetKeyWord(CharacterRoleCtrl, jsonTb)

			self[keyWord] = jsonTb
		end)

		CharacterRoleCtrl.hasCached = true
		CharacterRole.GetAllSync = nil
		CharacterRole.GetAllASync = nil
	end)
end

setmetatable(CharacterRole, {
	__index = function(tb, key)
		if not key or key == "" or key == 0 then
			return nil
		end

		if key == "GetAllASync" or key == "GetAllSync" then
			return function()
				print(key .. " could be called only once")
			end
		end

		local dicRow = SqlLiteSupport.ExecuteQueryOne("CharacterRole", SqlLiteTransfer.GenSql("CharacterRole", CharacterRoleCtrl, key))

		if dicRow then
			local jsonTb = SqlLiteTransfer.TransferFromJson(dicRow, CharacterRoleInfo)

			tb[key] = jsonTb

			return jsonTb
		else
			return nil
		end
	end
})
CharacterRole:GetAllSync()

return CharacterRole
