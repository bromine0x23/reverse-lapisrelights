function GetEmojiIdByType(itemtype)
	if itemtype == nil or eEmojiItemType[itemtype] == nil then
		return -1
	end

	return eEmojiItemType[itemtype] or -1
end

function GetEmojiId(itemId)
	local itemtype
	local item = ItemManager:Get(itemId)

	if item then
		itemtype = item.data.Type
	end

	if itemtype == nil or eEmojiItemType[itemtype] == nil then
		return -1
	end

	if itemtype == "I_DRAW" or itemtype == "I_AVATAR" then
		return eEmojiItemType[itemtype][itemId] or -1
	elseif itemtype == "I_SOUL" then
		return eEmojiItemType[itemtype][item.data.Level] or -1
	elseif itemtype == "I_AVATAR" then
		return eEmojiItemType[itemtype][itemId] or -1
	end

	return eEmojiItemType[itemtype] or -1
end

